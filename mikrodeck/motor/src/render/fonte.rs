#[cfg(test)]
mod testes {
    use super::*;

    #[test]
    fn tem_glifo_para_todo_ascii_visivel() {
        for c in ' '..='~' {
            assert!(glifo(c).is_some(), "faltou glifo para {c:?}");
        }
    }

    #[test]
    fn acento_cai_para_a_letra_sem_acento() {
        assert_eq!(glifo('á'), glifo('a'));
        assert_eq!(glifo('ç'), glifo('c'));
        assert_eq!(glifo('Ó'), glifo('O'));
    }

    #[test]
    fn caractere_fora_da_fonte_devolve_nada() {
        assert!(glifo('☃').is_none());
    }

    #[test]
    fn largura_bate_com_o_numero_de_caracteres() {
        assert_eq!(largura_do_texto(""), 0);
        assert_eq!(largura_do_texto("A"), 5);
        assert_eq!(largura_do_texto("AB"), 11);
        // 21 caracteres é o que cabe na tela de 128 pixels.
        assert!(largura_do_texto(&"A".repeat(21)) <= 128);
        assert!(largura_do_texto(&"A".repeat(22)) > 128);
    }
}
