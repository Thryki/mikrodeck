//! Fonte bitmap 5x7 para a tela do aparelho.
//!
//! A tela tem 128x32 pixels e 1 bit por pixel. Fonte vetorial não faz sentido aqui:
//! cada pixel é decidido na mão. Com 5x7 mais 1 de espaço cabem 21 caracteres por
//! linha e 4 linhas, o que é bastante para nome de página e de controle.
//!
//! Cada caractere são 5 bytes, um por coluna. Em cada byte, o bit 0 é a linha de cima.

/// Largura de um caractere em pixels, sem contar o espaço entre eles.
pub const LARGURA: usize = 5;
/// Altura de um caractere em pixels.
pub const ALTURA: usize = 7;
/// Espaço entre caracteres.
pub const ESPACO: usize = 1;
/// Quanto cada caractere avança na horizontal.
pub const AVANCO: usize = LARGURA + ESPACO;

/// Desenho de um caractere, ou `None` se não estiver na fonte.
pub fn glifo(c: char) -> Option<[u8; LARGURA]> {
    // Acentos comuns do português caem para a letra sem acento, para não
    // sumir texto na tela por falta de glifo.
    let c = match c {
        'á' | 'à' | 'â' | 'ã' | 'ä' => 'a',
        'é' | 'ê' | 'è' => 'e',
        'í' | 'î' | 'ì' => 'i',
        'ó' | 'ô' | 'õ' | 'ò' => 'o',
        'ú' | 'û' | 'ù' => 'u',
        'ç' => 'c',
        'Á' | 'À' | 'Â' | 'Ã' => 'A',
        'É' | 'Ê' => 'E',
        'Í' => 'I',
        'Ó' | 'Ô' | 'Õ' => 'O',
        'Ú' => 'U',
        'Ç' => 'C',
        outro => outro,
    };
    let i = (c as usize).checked_sub(32)?;
    TABELA.get(i).copied()
}

/// Largura em pixels que um texto vai ocupar.
pub fn largura_do_texto(texto: &str) -> usize {
    let n = texto.chars().count();
    if n == 0 { 0 } else { n * AVANCO - ESPACO }
}

